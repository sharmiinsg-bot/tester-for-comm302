// Helper to generate simulated candlestick price history for Supercharts
export function generateCandleData(basePrice: number, points = 35): CandleData[] {
  const candles: CandleData[] = [];
  let currentPrice = basePrice * 0.94;
  const now = new Date();
  
  for (let i = points; i >= 0; i--) {
    const timeDate = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const dateStr = timeDate.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
    
    const volatility = currentPrice * 0.016;
    const change = (Math.random() - 0.47) * volatility;
    const open = currentPrice;
    const close = Math.max(open + change, 1);
    const high = Math.max(open, close) + Math.random() * volatility * 0.6;
    const low = Math.min(open, close) - Math.random() * volatility * 0.6;
    const volume = Math.floor(Math.random() * 8000000 + 4000000);
    
    candles.push({
      time: dateStr,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume
    });
    
    currentPrice = close;
  }
  
  // ensure last candle matches basePrice
  if (candles.length > 0) {
    const last = candles[candles.length - 1];
    last.close = basePrice;
    last.high = Math.max(last.high, basePrice);
  }
  
  return candles;
}
